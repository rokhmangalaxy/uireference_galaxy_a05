/** Build an 8 KiB CHR image with tile n == ASCII glyph n. */
export function buildFontChr() {
  const chr = new Uint8Array(8192);
  for (const [ch, rows] of Object.entries(G)) {
    const code = ch.charCodeAt(0);
    if (code < 0 || code > 255) continue;
    for (let y = 0; y < 8; y++) {
      const row = rows[y] || "00000";
      let lo = 0;
      let hi = 0;
      for (let x = 0; x < 5; x++) {
        if (row[x] === "1") {
          lo |= 1 << (7 - x);
          hi |= 1 << (7 - x);
        }
      }
      const o = code * 16 + y;
      chr[o] = lo;
      chr[o + 8] = hi; // both bitplanes -> the glyph is white in every palette
    }
  }
  return chr;
}
